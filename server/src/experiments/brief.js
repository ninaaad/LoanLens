// Template-based decision brief (markdown). An LLM may later rephrase it (S6) but never changes the numbers or the decision.
import { PRIMARY_METRICS } from './analyse.js';

const pct = (x, d = 2) => (x === null || x === undefined ? 'n/a' : `${(x * 100).toFixed(d)}%`);
const pts = (x, d = 2) => (x === null || x === undefined ? 'n/a' : `${x >= 0 ? '+' : ''}${(x * 100).toFixed(d)} pts`);
const hrs = (s) => (s === null || s === undefined ? 'n/a' : `${(s / 3600).toFixed(2)} h`);

export function buildBrief(def, a, { cohort } = {}) {
  const [ctrl, treat] = def.variants.map((v) => v.name);
  const p = a.primary;
  const lines = [];
  lines.push(`# Experiment brief: ${def.name}`);
  lines.push('');
  lines.push('> **Synthetic data.** This cohort was generated by LoanLens with a known seeded effect. It illustrates the method; it is not evidence about real borrowers.');
  lines.push('');
  lines.push(`**Decision: ${a.decision.action.toUpperCase()}**`);
  for (const r of a.decision.reasons) lines.push(`- ${r}`);
  lines.push('');
  lines.push('## Hypothesis');
  lines.push(def.hypothesis);
  lines.push('');
  lines.push('## Setup');
  lines.push(`- Key: \`${def.key}\`; primary metric: ${PRIMARY_METRICS[def.primary_metric].label}.`);
  lines.push(`- Variants: ${def.variants.map((v) => `${v.name} (${v.weight}%)`).join(', ')}. Assignment is deterministic: hash(unit id + key) mod 100.`);
  lines.push(`- Users analysed: ${a.exposure[ctrl]} ${ctrl}, ${a.exposure[treat]} ${treat}.${cohort ? ` Seed ${cohort.seed}.` : ''}`);
  lines.push('');
  lines.push('## Primary result');
  lines.push(`| Metric | ${ctrl} | ${treat} | Difference | 95% CI | p-value |`);
  lines.push('|---|---|---|---|---|---|');
  lines.push(`| ${p.label} | ${pct(p.control)} | ${pct(p.treatment)} | ${pts(p.diff)} (${p.relative_lift === null ? 'n/a' : `${(p.relative_lift * 100).toFixed(1)}%`} relative) | ${pts(p.ci95[0])} to ${pts(p.ci95[1])} | ${p.p_value === null ? 'n/a' : p.p_value.toFixed(4)} |`);
  if (p.mde80) lines.push(`
Sensitivity: with ${a.exposure[ctrl]} and ${a.exposure[treat]} users this test would detect a true difference of about ${(p.mde80 * 100).toFixed(2)} points or more 80% of the time. A smaller real effect would usually go unseen.`);
  lines.push('');
  lines.push('## Guardrails');
  lines.push(`| Guardrail | ${ctrl} | ${treat} | Change | 95% CI | Tolerance | Status |`);
  lines.push('|---|---|---|---|---|---|---|');
  for (const g of a.guardrails) {
    if (g.status === 'no_data') { lines.push(`| ${g.label} | n/a | n/a | n/a | n/a | n/a | no data |`); continue; }
    const isTime = g.metric === 'median_tat';
    const tol = g.tolerance.type === 'rel' ? `+${(g.tolerance.value * 100).toFixed(0)}%` : `+${(g.tolerance.value * 100).toFixed(2)} pts`;
    lines.push(isTime
      ? `| ${g.label} | ${hrs(g.control)} | ${hrs(g.treatment)} | ${(g.delta_relative * 100).toFixed(1)}% | ${hrs(g.ci95[0])} to ${hrs(g.ci95[1])} (difference) | ${tol} | ${g.status} |`
      : `| ${g.label} | ${pct(g.control)} | ${pct(g.treatment)} | ${pts(g.delta)} | ${pts(g.ci95[0])} to ${pts(g.ci95[1])} | ${tol} | ${g.status} |`);
  }
  lines.push('');
  lines.push('## Data quality');
  lines.push(`- Sample ratio check: observed ${a.srm.observed.join(' / ')}, expected ${a.srm.expected.join(' / ')}; chi-square ${a.srm.chi2} (df ${a.srm.df}), p = ${a.srm.p < 0.0001 ? a.srm.p.toExponential(2) : a.srm.p.toFixed(4)}. ${a.srm.flagged ? '**Mismatch flagged.**' : 'No mismatch.'}`);
  lines.push('');
  lines.push('## Decision rule');
  lines.push(a.decision.rule + '.');
  lines.push('');
  lines.push('## Caveats');
  lines.push('- Synthetic cohort with a seeded true effect; real traffic would add novelty effects, seasonality and interference.');
  lines.push('- A single look at the data; no correction for repeated peeking or for multiple guardrails.');
  lines.push('- Median turnaround time uses a normal approximation for the interval; the complaint rate is a proxy, not real complaints.');
  lines.push('- "Status ok" means the 95% interval sits within tolerance; "uncertain" means it straddles the tolerance.');
  return lines.join('\n');
}
